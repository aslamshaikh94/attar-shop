-- Attar & Perfume Shop - Supabase Schema
-- Initial database schema and seed data.

-- Partners
create table partners (
  id bigint generated by default as identity primary key,
  name text not null,
  role text not null,
  share_percent numeric not null default 50,
  created_at timestamptz default now()
);

-- Products / Stock
create table products (
  id bigint generated by default as identity primary key,
  name text not null,
  type text not null,
  category text,
  buying_price numeric not null default 0,
  selling_price numeric not null default 0,
  stock_qty numeric not null default 0,
  unit text default 'ml',
  created_at timestamptz default now()
);

-- Purchases (stock in)
create table purchases (
  id bigint generated by default as identity primary key,
  product_id bigint references products(id) on delete cascade,
  qty numeric not null,
  unit_price numeric not null,
  total_price numeric not null,
  supplier text,
  note text,
  date date not null,
  created_at timestamptz default now()
);

-- Sales (stock out)
create table sales (
  id bigint generated by default as identity primary key,
  product_id bigint references products(id) on delete cascade,
  qty numeric not null,
  unit_price numeric not null,
  total_price numeric not null,
  cost_price numeric not null default 0,
  customer text,
  payment_method text not null default 'Cash',
  note text,
  date date not null,
  created_at timestamptz default now()
);

-- Expenses
create table expenses (
  id bigint generated by default as identity primary key,
  title text not null,
  amount numeric not null,
  category text,
  date date not null,
  note text,
  created_at timestamptz default now()
);

-- Partner drawings (money taken out by partners)
create table partner_drawings (
  id bigint generated by default as identity primary key,
  partner_id bigint references partners(id) on delete cascade,
  amount numeric not null,
  date date not null,
  note text,
  created_at timestamptz default now()
);

